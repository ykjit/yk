//! Deal with setting threads and shadowstacks up.

use std::os::raw::{c_int, c_void};

use libc::{free, malloc, pthread_create};
use parking_lot::Mutex;
use std::cell::OnceCell;
use std::sync::atomic::{AtomicUsize, Ordering};
use ykaddr::addr::symbol_to_ptr;

thread_local! {
    /// This thread's shadowstack memory (when it's actually allocated).
    static THREAD_SHADOW_STACK: OnceCell<ShadowStack> = const { OnceCell::new() };
}

/// The default shadow stack size (4MiB).
static DEFAULT_SHADOW_STACK_SIZE: AtomicUsize = AtomicUsize::new(4 * 1024 * 1024);
/// A global record of all threads' shadowstacks.
static SHADOW_STACKS: Mutex<Vec<ShadowStack>> = Mutex::new(Vec::new());

#[derive(Clone, Copy, Debug)]
struct ShadowStack {
    start: *mut c_void,
    size: usize,
}
unsafe impl Send for ShadowStack {}

/// Called by code generated by ykllvm.
pub fn alloc_main_shadowstack() -> *mut c_void {
    allocate_shadowstack(DEFAULT_SHADOW_STACK_SIZE.load(Ordering::Relaxed))
}

/// Set the process-wide shadow stack size for future threads.
pub fn set_default_shadowstack_size(size: usize) {
    assert!(size != 0 && size <= isize::MAX.cast_unsigned());
    DEFAULT_SHADOW_STACK_SIZE.store(size, Ordering::Relaxed);
}

fn allocate_shadowstack(size: usize) -> *mut c_void {
    let start = unsafe { malloc(size) };
    if start.is_null() {
        panic!("Unable to allocate shadow stack");
    }
    let stack = ShadowStack { start, size };
    THREAD_SHADOW_STACK.with(|oc| oc.set(stack).unwrap());
    SHADOW_STACKS.lock().push(stack);
    start
}

#[derive(Debug)]
struct Target {
    func: extern "C" fn(*mut c_void) -> *mut c_void,
    arg: *mut c_void,
}

/// Call a function for each shadow stack.
pub fn yk_foreach_shadowstack(f: extern "C" fn(*mut c_void, *mut c_void)) {
    for stack in SHADOW_STACKS.lock().iter() {
        f(stack.start, stack.start.wrapping_byte_add(stack.size));
    }
}

/// Return the start and current end (i.e. only the used portion) of the current thread's shadow
/// stack.
pub fn yk_thread_shadowstack_bounds() -> (*mut c_void, *mut c_void) {
    let start = THREAD_SHADOW_STACK.with(|oc| oc.get().unwrap().start);
    let end = unsafe { *(symbol_to_ptr("shadowstack_0").unwrap() as *mut *mut c_void) };
    assert!(start <= end);
    (start, end)
}

/// The function is called just after a new thread has been created by `pthread_create`. We use it
/// to create a new shadow stack, and then call the "real" `routine` passed to `pthread_create`.
extern "C" fn wrap_thread_start(tgt: *mut c_void) -> *mut c_void {
    let tgt = unsafe { Box::from_raw(tgt as *mut Target) };
    // Obtain address of a shadowstack_0 symbol
    let shadowstack_0 = symbol_to_ptr("shadowstack_0").unwrap() as *mut *mut c_void;
    let newsstack = allocate_shadowstack(DEFAULT_SHADOW_STACK_SIZE.load(Ordering::Relaxed));
    unsafe { *shadowstack_0 = newsstack };
    // Call the `routine` passed to `pthread_create`.
    let ret = (tgt.func)(tgt.arg);
    {
        // Remove the allocation before freeing it so that `foreach_shadowstack` sees a consistent
        // view.
        let mut lk = SHADOW_STACKS.lock();
        let idx = lk.iter().position(|s| s.start == newsstack).unwrap();
        lk.swap_remove(idx);
    }
    unsafe { free(newsstack) };
    ret
}

/// Wraps system pthread create
#[unsafe(no_mangle)]
pub extern "C" fn __wrap_pthread_create(
    thread: *mut libc::pthread_t,
    attr: *const libc::pthread_attr_t,
    start_routine: extern "C" fn(*mut c_void) -> *mut c_void,
    arg: *mut c_void,
) -> c_int {
    let tgt = Box::new(Target {
        func: start_routine,
        arg,
    });
    let tgt = Box::into_raw(tgt);
    let ret = unsafe { pthread_create(thread, attr, wrap_thread_start, tgt.cast()) };
    if ret != 0 {
        unsafe { drop(Box::from_raw(tgt)) };
    }
    ret
}

